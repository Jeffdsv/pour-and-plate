-- V1: initial schema for the tasting service.
-- Flyway runs this once and records it in the table flyway_schema_history.
-- NEVER edit this file after it has run. Changes go in a new file: V2__..., V3__...

-- ============ THINGS ============

CREATE TABLE restaurant (
                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name        VARCHAR(200) NOT NULL,
                            city        VARCHAR(100),
                            address     VARCHAR(255),
                            cuisine     VARCHAR(100),
                            latitude    NUMERIC(9, 6),   -- 6 decimals = about 10 cm precision, plenty for a map
                            longitude   NUMERIC(9, 6),
                            created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE wine (
                      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name        VARCHAR(200) NOT NULL,
                      producer    VARCHAR(200),
                      country     VARCHAR(100),
                      region      VARCHAR(100),
                      wine_type   VARCHAR(20)  NOT NULL
                          CHECK (wine_type IN ('RED', 'WHITE', 'ROSE', 'SPARKLING', 'ORANGE', 'DESSERT')),
                      grape       VARCHAR(200),    -- free text for now, e.g. "Nebbiolo" or "Cabernet Sauvignon, Merlot"
                      vintage     INTEGER CHECK (vintage BETWEEN 1800 AND 2100),
                      abv         NUMERIC(4, 1) CHECK (abv BETWEEN 0 AND 100),
                      created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE beer (
                      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name        VARCHAR(200) NOT NULL,
                      brewery     VARCHAR(200),
                      country     VARCHAR(100),
                      style       VARCHAR(100),    -- IPA, Stout, Sour, Lager ...
                      abv         NUMERIC(4, 1) CHECK (abv BETWEEN 0 AND 100),
                      created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============ EXPERIENCES ============

CREATE TABLE wine_tasting (
                              id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              wine_id        BIGINT NOT NULL REFERENCES wine (id),                          -- can't delete a wine that has tastings
                              restaurant_id  BIGINT REFERENCES restaurant (id) ON DELETE SET NULL,          -- optional: where you drank it
                              rating         INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 10),
                              notes          TEXT,
                              price_sek      NUMERIC(10, 2) CHECK (price_sek >= 0),
                              tasted_on      DATE NOT NULL DEFAULT CURRENT_DATE,
                              created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE beer_tasting (
                              id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              beer_id        BIGINT NOT NULL REFERENCES beer (id),
                              restaurant_id  BIGINT REFERENCES restaurant (id) ON DELETE SET NULL,
                              rating         INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 10),
                              notes          TEXT,
                              price_sek      NUMERIC(10, 2) CHECK (price_sek >= 0),
                              tasted_on      DATE NOT NULL DEFAULT CURRENT_DATE,
                              created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE restaurant_visit (
                                  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  restaurant_id      BIGINT NOT NULL REFERENCES restaurant (id),
                                  food_rating        INTEGER NOT NULL CHECK (food_rating BETWEEN 1 AND 10),
                                  atmosphere_rating  INTEGER NOT NULL CHECK (atmosphere_rating BETWEEN 1 AND 10),
                                  value_rating       INTEGER NOT NULL CHECK (value_rating BETWEEN 1 AND 10),
                                  notes              TEXT,
                                  total_price_sek    NUMERIC(10, 2) CHECK (total_price_sek >= 0),
                                  visited_on         DATE NOT NULL DEFAULT CURRENT_DATE,
                                  created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
    -- No overall_rating column: it's calculated as (food + atmosphere + value) / 3
);

-- Postgres does NOT index foreign keys automatically. These make
-- "all tastings of wine X" and "all visits to restaurant Y" fast.
CREATE INDEX idx_wine_tasting_wine        ON wine_tasting (wine_id);
CREATE INDEX idx_wine_tasting_restaurant  ON wine_tasting (restaurant_id);
CREATE INDEX idx_beer_tasting_beer        ON beer_tasting (beer_id);
CREATE INDEX idx_beer_tasting_restaurant  ON beer_tasting (restaurant_id);
CREATE INDEX idx_restaurant_visit_rest    ON restaurant_visit (restaurant_id);
