-- V8: invite links, only the admin can create them
-- the token itself is never stored, only its sha 256 hash, so a leaked database gives no working links
CREATE TABLE invite (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        token_hash  VARCHAR(64) NOT NULL UNIQUE,
                        created_by  BIGINT NOT NULL REFERENCES app_user (id),
                        expires_at  TIMESTAMPTZ NOT NULL,
                        used_at     TIMESTAMPTZ,                       -- empty until someone signs up with it
                        used_by     BIGINT REFERENCES app_user (id),   -- the friend who signed up
                        created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
                        updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);