-- V2: restaurants only. Wine/beer come back later as pairings.

-- Remove the old V1 tables
DROP TABLE wine_tasting, beer_tasting, restaurant_visit, wine, beer, restaurant;

CREATE TABLE restaurant
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_id            VARCHAR(50) UNIQUE,     -- OpenStreetMap id, e.g. "node/123456"
    name              VARCHAR(200)  NOT NULL,
    address           VARCHAR(255),
    city              VARCHAR(100),
    latitude          NUMERIC(9, 6) NOT NULL, -- needed for the pin
    longitude         NUMERIC(9, 6) NOT NULL,
    status            VARCHAR(20)   NOT NULL
        CHECK (status IN ('VISITED', 'WANT_TO_VISIT')),
    food_rating       INTEGER CHECK (food_rating BETWEEN 1 AND 10),
    atmosphere_rating INTEGER CHECK (atmosphere_rating BETWEEN 1 AND 10),
    value_rating      INTEGER CHECK (value_rating BETWEEN 1 AND 10),
    notes             TEXT,
    visited_on        DATE,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    -- VISITED needs all 3 ratings, WANT_TO_VISIT has none
    CONSTRAINT ratings_match_status CHECK (
        (status = 'VISITED'
            AND food_rating IS NOT NULL
            AND atmosphere_rating IS NOT NULL
            AND value_rating IS NOT NULL)
            OR
        (status = 'WANT_TO_VISIT'
            AND food_rating IS NULL
            AND atmosphere_rating IS NULL
            AND value_rating IS NULL)
        )
);

-- Makes "show all my want-to-visit places" fast
CREATE INDEX idx_restaurant_status ON restaurant (status);