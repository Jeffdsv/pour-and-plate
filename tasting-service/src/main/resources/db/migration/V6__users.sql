CREATE TABLE app_user (
                          id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          username       VARCHAR(50)  NOT NULL UNIQUE,     -- what you log in with
                          display_name   VARCHAR(100) NOT NULL,            -- what others see in the list
                          password_hash  VARCHAR(100),                     -- never the real password, empty until set on first start
                          role           VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'FRIEND')),
                          created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
                          updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

